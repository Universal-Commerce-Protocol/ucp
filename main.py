def _load_openapi(file_name: str) -> dict[str, Any]:
  with (OPENAPI_DIR / file_name).open(encoding="utf-8") as f:
    return json.load(f)


def _find_operation(
  data: dict, operation_id: str, include_webhooks: bool
) -> tuple[dict | None, list]:
  """Find an operation by id; return it with its path-level parameters."""
  sections = [data.get("paths", {})]
  if include_webhooks:
    sections.append(data.get("webhooks", {}))  # OpenAPI 3.1+
  for section in sections:
    for path_item in section.values():
      for op_data in path_item.values():
        if isinstance(op_data, dict) and (
          op_data.get("operationId") == operation_id
        ):
          return op_data, path_item.get("parameters", [])
  return None, []


def _security_header_rows(data: dict, operation: dict) -> list[dict]:
  """Header rows for the authentication schemes an operation accepts.

  OpenAPI 3.1 ignores a header parameter named Authorization, so auth belongs
  in security/securitySchemes; a header table built only from parameters
  silently stops listing authentication once a spec declares it correctly.
  """
  requirements = operation.get("security", data.get("security", []))
  schemes = data.get("components", {}).get("securitySchemes", {})
  scheme_names: dict[str, list[str]] = {}
  descriptions: dict[str, list[str]] = {}
  for name in dict.fromkeys(n for r in requirements for n in r):
    scheme = schemes.get(name, {})
    kind = scheme.get("type")
    if kind == "http":
      header = "Authorization"
      auth = scheme.get("scheme", "")
      prefix = f"`{auth.capitalize()}` credentials. " if auth else ""
    elif kind in ("oauth2", "openIdConnect"):
      header = "Authorization"
      prefix = "`Bearer` access token. "
    elif kind == "apiKey" and scheme.get("in") == "header":
      header = scheme.get("name", "")
      prefix = ""
    else:
      continue
    if not header:
      continue
    scheme_names.setdefault(header, []).append(name)
    descriptions.setdefault(header, []).append(
      prefix + scheme.get("description", "")
    )
  return [
    {
      "name": header,
      # Required only when every alternative needs one of these schemes.
      "required": all(any(n in r for n in names) for r in requirements),
      "description": " ".join(descriptions[header]).strip(),
    }
    for header, names in scheme_names.items()
  ]


def _content_header_rows(data: dict, operation: dict) -> list[dict]:
  """Content-Type/Accept rows derived from the operation's media types.

  OpenAPI 3.1 ignores Content-Type and Accept header parameters; the request
  body and response content maps are where those are actually declared.
  """

  def resolved(node: Any) -> dict:
    if isinstance(node, dict) and "$ref" in node:
      return _resolve_json_pointer(node["$ref"], data) or {}
    return node if isinstance(node, dict) else {}

  rows = []
  body = resolved(operation.get("requestBody")).get("content", {})
  if body:
    types = ", ".join(f"`{t}`" for t in body)
    rows.append(
      {
        "name": "Content-Type",
        "required": False,
        "description": f"Media type of the request body: {types}.",
      }
    )
  for code, response in sorted(operation.get("responses", {}).items()):
    if not str(code).startswith("2"):
      continue
    content = resolved(response).get("content")
    if content:
      types = ", ".join(f"`{t}`" for t in content)
      rows.append(
        {
          "name": "Accept",
          "required": False,
          "description": f"Response media types the client accepts: {types}.",
        }
      )
      break
  return rows


def _resolve_raw_ref(
  ref: str,
  schema_path: Path | None,
  raw_root: dict[str, Any] | None,
) -> tuple[dict[str, Any] | None, Path | None, dict[str, Any] | None]:
  """Resolve a `$ref` against its unbundled source schema document."""
  if not isinstance(ref, str) or not ref:
    return None, schema_path, raw_root
  if ref == "#":
    return raw_root, schema_path, raw_root
  if ref.startswith("#/"):
    if isinstance(raw_root, dict):
      target = _resolve_json_pointer(ref, raw_root)
      return (
        target if isinstance(target, dict) else None,
        schema_path,
        raw_root,
      )
    return None, schema_path, raw_root
  if schema_path is None:
    return None, None, None
  if "#" in ref:
    rel_file, frag = ref.split("#", 1)
    frag = "#" + frag
  else:
    rel_file, frag = ref, None
  target_path = (schema_path.parent / rel_file).resolve()
  if not target_path.exists():
    return None, schema_path, raw_root
  target_root = _resolve_schema(target_path)
  if not isinstance(target_root, dict):
    return None, target_path, None
  target_node = (
    _resolve_json_pointer(frag, target_root) if frag else target_root
  )
  return (
    target_node if isinstance(target_node, dict) else None,
    target_path,
    target_root,
  )


def _restore_fragment_refs(
  bundled_def: dict[str, Any],
  raw_def: dict[str, Any] | None,
  schema_path: Path | None = None,
  raw_root: dict[str, Any] | None = None,
  *,
  root_schema_path: Path | None = None,
  anchor_checker: Any = None,
) -> dict[str, Any]:
  """Restore `$ref`s and fragment titles that bundling inlined without `$id`.

  Bundling (`ucp-schema resolve --bundle`) inlines every `$ref` and (starting
  in `ucp-schema` 2.0.0) strips non-root `$id`s from inlined schemas, which
  leaves the table renderer with no link target and degrades Type cells to
  `object` or `Array[object]`. Walk the bundled definition alongside the
  unbundled definition across `properties`, `items`, dict
  `additionalProperties`, `allOf`, `oneOf`, and `anyOf`:
  - Whole-file cross-file `$ref`s are restored unconditionally.
  - Fragment `$ref`s (including `#/$defs/...` inside a cross-file schema
    reached via `allOf`, rewritten relative to `root_schema_path`) are
    restored only when `anchor_checker` confirms a real anchor on the target
    page; otherwise the target definition's `title` (if any) is copied onto
    the bundled node as a human-readable fallback.
  - `ucp.json` targets are skipped because the renderer handles those itself.

  Args:
    bundled_def: The bundled definition to be rendered.
    raw_def: The same definition resolved without bundling.
    schema_path: Path to the schema file `raw_def` was loaded from.
    raw_root: Full unbundled schema document containing `raw_def`.
    root_schema_path: Path to the outermost schema file being rendered.
    anchor_checker: Optional callable `fn(ref_str) -> bool` returning True
      when `ref_str` resolves to an existing anchor on its target spec page.

  Returns:
    bundled_def, with lost `$ref`s and fallback titles restored.

  """
  orig_root_path = (
    (root_schema_path or schema_path).resolve()
    if (root_schema_path or schema_path) is not None
    else None
  )

  def _walk(
    bundled: Any,
    raw: Any,
    cur_path: Path | None,
    cur_root: dict[str, Any] | None,
    *,
    table_level: bool,
  ) -> Any:
    if not isinstance(bundled, dict) or not isinstance(raw, dict):
      return bundled

    if (
      not table_level
      and isinstance(raw.get("$ref"), str)
      and "$ref" not in bundled
      and "$id" not in bundled
    ):
      ref = raw["$ref"]
      # Follow same-file #/$defs/... aliases that forward to another $ref
      # (e.g. fulfillment.json#/$defs/fulfillment -> types/fulfillment.json).
      seen_local: set[str] = set()
      while (
        isinstance(ref, str)
        and ref.startswith("#/")
        and ref not in seen_local
        and isinstance(cur_root, dict)
      ):
        seen_local.add(ref)
        target = _resolve_json_pointer(ref, cur_root)
        if isinstance(target, dict) and isinstance(target.get("$ref"), str):
          ref = target["$ref"]
        else:
          break

      targets_ucp = "ucp.json" in ref or (
        cur_path is not None
        and cur_path.name == "ucp.json"
        and ref.startswith("#")
      )
      if ref and not targets_ucp:
        candidate_ref = ref
        if (
          cur_path is not None
          and orig_root_path is not None
          and cur_path.resolve() != orig_root_path
        ):
          rel_from_root = Path(
            os.path.relpath(cur_path.resolve(), orig_root_path.parent)
          ).as_posix()
          if ref == "#":
            candidate_ref = rel_from_root
          elif ref.startswith("#/"):
            candidate_ref = f"{rel_from_root}{ref}"

        if "#" not in candidate_ref or candidate_ref == "#":
          return {**bundled, "$ref": candidate_ref}
        if anchor_checker is not None and anchor_checker(candidate_ref):
          return {**bundled, "$ref": candidate_ref}

    # Follow $ref on raw when bundling inlined its target so we can copy any
    # fallback title and walk nested composition/properties in lockstep.
    seen_refs: set[tuple[Path | None, str]] = set()
    while (
      isinstance(raw, dict)
      and isinstance(raw.get("$ref"), str)
      and "$ref" not in bundled
      and (cur_path, raw["$ref"]) not in seen_refs
    ):
      ref_str = raw["$ref"]
      seen_refs.add((cur_path, ref_str))
      resolved_node, next_path, next_root = _resolve_raw_ref(
        ref_str, cur_path, cur_root
      )
      if not isinstance(resolved_node, dict):
        break
      if (
        not table_level and "title" in resolved_node and "title" not in bundled
      ):
        bundled = {**bundled, "title": resolved_node["title"]}
      elif (
        not table_level
        and "title" not in bundled
        and "#/$defs/" in ref_str
        and "ucp.json" not in ref_str
      ):
        bundled = {
          **bundled,
          "x-ucp-def-name": (
            ref_str.rsplit("/", 1)[-1].replace("_", " ").title()
          ),
        }
      merged_raw = dict(resolved_node)
      for k, v in raw.items():
        if k != "$ref":
          merged_raw[k] = v
      raw = merged_raw
      cur_path = next_path
      cur_root = next_root

    result = dict(bundled)

    if isinstance(result.get("properties"), dict) and isinstance(
      raw.get("properties"), dict
    ):
      raw_props = raw["properties"]
      result["properties"] = {
        name: _walk(
          details, raw_props.get(name), cur_path, cur_root, table_level=False
        )
        for name, details in result["properties"].items()
      }

    if isinstance(result.get("items"), dict) and isinstance(
      raw.get("items"), dict
    ):
      result["items"] = _walk(
        result["items"], raw["items"], cur_path, cur_root, table_level=False
      )

    if isinstance(result.get("additionalProperties"), dict) and isinstance(
      raw.get("additionalProperties"), dict
    ):
      result["additionalProperties"] = _walk(
        result["additionalProperties"],
        raw["additionalProperties"],
        cur_path,
        cur_root,
        table_level=False,
      )

    for keyword, child_table_level in (
      ("allOf", table_level),
      ("oneOf", False),
      ("anyOf", False),
    ):
      b_list = result.get(keyword)
      r_list = raw.get(keyword)
      if isinstance(b_list, list) and isinstance(r_list, list):
        r_entries = [(r_item, cur_path, cur_root) for r_item in r_list]
        # Bundling flattens pure `{"$ref": ...}` branches whose target is an
        # `allOf`-only schema (e.g. `capability.json#/$defs/response_schema`).
        while keyword == "allOf" and len(r_entries) < len(b_list):
          expanded_entries = []
          changed = False
          for r_item, r_path, r_root in r_entries:
            if isinstance(r_item, dict) and set(r_item) == {"$ref"}:
              t_node, t_path, t_root = _resolve_raw_ref(
                r_item["$ref"], r_path, r_root
              )
              if isinstance(t_node, dict) and isinstance(
                t_node.get("allOf"), list
              ):
                expanded_entries.extend(
                  (sub, t_path, t_root) for sub in t_node["allOf"]
                )
                changed = True
                continue
            expanded_entries.append((r_item, r_path, r_root))
          if not changed or len(expanded_entries) > len(b_list):
            break
          r_entries = expanded_entries
        if len(b_list) == len(r_entries):
          result[keyword] = [
            _walk(b_item, r_item, r_path, r_root, table_level=child_table_level)
            for b_item, (r_item, r_path, r_root) in zip(
              b_list, r_entries, strict=True
            )
          ]

    return result

  return _walk(bundled_def, raw_def, schema_path, raw_root, table_level=True)


def define_env(env):
  """Injects custom macros into the MkDocs environment.

  This function is called by MkDocs and receives the `env` object,
  allowing it to register custom macros like `schema_fields` and
  `method_fields` for use in Markdown pages.

  Args:
  ----
    env: The MkDocs environment object.

  """
  nav = getattr(env, "conf", {}).get("nav")
  page_index = build_spec_page_index(nav)

  ucp_type_index: dict[str, Any] = {}

  def _ucp_type_index() -> dict[str, Any]:
    """Load ucp.json $defs and the anchors reference.md defines for them."""
    if not ucp_type_index:
      ucp_type_index["defs"] = (_load_json(UCP_SCHEMA_PATH) or {}).get(
        "$defs", {}
      )
      try:
        reference_md = REFERENCE_DOC_PATH.read_text(encoding="utf-8")
      except OSError:
        reference_md = ""
      ucp_type_index["anchors"] = set(
        re.findall(r"\{: #(ucp-[a-z0-9-]+) \}", reference_md)
      )
    return ucp_type_index

  def _ucp_def_type(def_name: str) -> str:
    """Type cell for a field typed by a ucp.json $def.

    Links to the reference section anchored for the def (e.g.
    `{: #ucp-response-checkout-schema }`) when one exists, otherwise names
    the def by its title, so the cell never falls back to "any".
    """
    index = _ucp_type_index()
    resolved_def = index["defs"].get(def_name, {})
    title = resolved_def.get("title") or (
      "UCP " + def_name.replace("_", " ").title()
    )
    anchor = "ucp-" + def_name.replace("_", "-")
    if anchor in index["anchors"]:
      return f"[{title}](site:specification/reference/#{anchor})"
    return title

  def _ucp_def_name_for_title(title: str | None) -> str | None:
    """Find the ucp.json $def a bundled (already inlined) schema came from."""
    if not title:
      return None
    for def_name, def_schema in _ucp_type_index()["defs"].items():
      if isinstance(def_schema, dict) and def_schema.get("title") == title:
        return def_name
    return None

  def _variant_base(schema_path: Path) -> dict[str, Any] | None:
    """Return the schema that composes `schema_path` as an if/then variant.

    A per-type variant (e.g. media_video.json) is selected by its base via
    `allOf: [{"if": {...}, "then": {"$ref": "media_video.json"}}]`. The variant
    carries no back-pointer, so the relationship is read from the siblings
    that declare it rather than from a macro parameter a caller could omit.
    """
    for sibling in sorted(schema_path.parent.glob("*.json")):
      if sibling == schema_path:
        continue
      data = _load_json(sibling)
      if not data:
        continue
      for branch in data.get("allOf", []):
        then = branch.get("then") if isinstance(branch, dict) else None
        if isinstance(then, dict) and then.get("$ref") == schema_path.name:
          return data
    return None

  def _inherit_base_fields(
    schema_data: dict[str, Any], base_schema: dict[str, Any]
  ) -> tuple[dict[str, Any], list[str]]:
    """Complete a variant's description-only properties from its base.

    A variant property that carries only a `description` refines a field the
    base defines; its type, format, and requirement live on the base. Rendered
    standalone, such a row shows `any` / `Optional` directly under a base table
    that says `string` / `Required`. Copy the base definition and keep the
    variant's description so the row renders what actually validates.

    Returns the completed schema and the base's `required` list, to be passed
    as `parent_required_list`.
    """
    base_props = base_schema.get("properties", {})
    props = dict(schema_data.get("properties", {}))
    for name, details in props.items():
      if (
        isinstance(details, dict)
        and set(details) == {"description"}
        and name in base_props
      ):
        merged = dict(base_props[name])
        merged["description"] = details["description"]
        props[name] = merged
    completed = dict(schema_data)
    completed["properties"] = props
    return completed, base_schema.get("required", [])

  # --- Page context ---
  def get_error_context():
    try:
      return f" (in file: {env.page.file.src_path})"
    except AttributeError:
      return ""

  def _env_page_id() -> str | None:
    try:
      return _page_id(env.page.file.src_path)
    except AttributeError:
      return None

  def _page_vertical(spec_file_name: str | None) -> str | None:
    """Vertical of the calling page (from spec_file_name or the page path)."""
    return _vertical_of_page(spec_file_name) or _vertical_of_page(
      _env_page_id()
    )

  def _current_page(spec_file_name: str) -> str:
    """Page that same-page links resolve against."""
    if spec_file_name in page_index.pages:
      return spec_file_name
    return _env_page_id() or spec_file_name

  def _resolve(ref: str, ctx: "RenderContext") -> Path | None:
    """Resolve `ref` within `ctx`; ambiguity errors carry the page."""
    try:
      return resolve_ref(ref, ctx.base, ctx.lookup_vertical)
    except LookupError as e:
      raise LookupError(f"{e}{get_error_context()}") from e

  def _load_schema(path: Path, ctx: RenderContext) -> dict | None:
    """Load a schema, resolved for ctx's operation when io_type is set."""
    if not ctx.io_type:
      return _load_json(path)
    # No fallback to raw JSON: annotations must be resolved by ucp-schema.
    return _resolve_schema(path, ctx.io_type, ctx.operation)

  # --- Links ---
  _polymorphic_cache: dict[Path, bool] = {}

  def _is_polymorphic_type(ref_string: str, ctx: RenderContext) -> bool:
    """Check if a types/ schema is polymorphic (has ucp_request annotations).

    Polymorphic types have different request/response variants and require
    the -response suffix in anchors to match markdown headings.
    """
    if "types/" not in ref_string:
      return False
    path = _resolve(ref_string, ctx)
    if path is None:
      return False
    if path not in _polymorphic_cache:
      properties = (_load_json(path) or {}).get("properties", {})
      _polymorphic_cache[path] = any(
        isinstance(details, dict) and "ucp_request" in details
        for details in properties.values()
      )
    return _polymorphic_cache[path]

  def _link_destination(
    target: Path | None,
    ref_path: str,
    fragment: str | None,
    spec_file_name: str,
    anchor: str,
  ) -> tuple[str, str]:
    """Pick the (page, anchor) documenting `target` (see module docstring)."""
    current_page = _current_page(spec_file_name)
    if target is None:
      looks_common = "/common/" in ref_path or ref_path.startswith("common/")
      return (REFERENCE_PAGE if looks_common else current_page), anchor

    if not _is_within(target, SCHEMAS_DIR) or vertical_of(target) is None:
      # Common files canonically live on the reference page; internal refs
      # (`#/...`) of common, protocol (ucp.json, ...) and OpenAPI documents
      # stay on the page rendering that document.
      is_internal = not ref_path.split("#", 1)[0]
      if not is_internal and _is_within(target, COMMON_SCHEMAS_DIR):
        return REFERENCE_PAGE, anchor
      return current_page, anchor

    # Vertical schema: route by the exact file, never by its basename.
    if page_index.hosts(current_page, target):
      return current_page, anchor
    if current_page != REFERENCE_PAGE and target in page_index.canonical:
      return page_index.canonical[target], anchor
    return REFERENCE_PAGE, reference_anchor(target, fragment)

  def create_link(ref_string, spec_file_name, ctx=None):
    """Transform a schema reference into a Markdown link.

    Args:
    ----
      ref_string: e.g. "types/line_item.json",
        "../../common/types/pagination.json#/$defs/response" or
        "#/$defs/allocation".
      spec_file_name: The page the link is rendered on, e.g.
        "shopping/checkout".
      ctx: Optional RenderContext of the table containing the link. Its
        `base` resolves relative refs; its `io_type` drives polymorphic
        labels.

    Returns:
    -------
      Markdown link, e.g.
      [Line Item](site:specification/shopping/checkout/#line-item).

    """
    ctx = ctx or RenderContext(vertical=_page_vertical(spec_file_name))
    ref_path, _, fragment = ref_string.partition("#/$defs/")
    fragment = fragment or None
    raw_name = Path(ref_path).name.replace(".json", "")
    is_ucp = "ucp.json" in ref_string

    link_text = _link_text(raw_name, fragment, is_ucp)
    anchor = _link_anchor(raw_name, fragment, is_ucp)

    # For polymorphic types in response mode, keep the base anchor name to
    # match markdown headings like "Line Item", but label it as a response.
    is_plain_name = (
      not fragment
      and "." not in raw_name
      and not raw_name.endswith(("_resp", "_req"))
    )
    if (
      is_plain_name
      and ctx.io_type == "response"
      and _is_polymorphic_type(ref_string, ctx)
      and not link_text.endswith("Response")
    ):
      link_text = f"{link_text} Response"

    target = _resolve(ref_path or "#", ctx)
    page, anchor = _link_destination(
      target, ref_path, fragment, spec_file_name, anchor
    )
    return f"[{link_text}](site:specification/{page}/#{anchor})"

  # --- Anchor verification ---
  def _slugify_heading(text: str) -> str:
    """Slugify a Markdown heading using Python-Markdown `toc` rules."""
    parts = re.split(r"`([^`]*)`", text)
    clean = "".join(
      part if idx % 2 == 1 else re.sub(r"[*_~]", "", part)
      for idx, part in enumerate(parts)
    )
    clean = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", clean)
    clean = re.sub(r"<[^>]+>", "", clean)
    clean = re.sub(r"\s+#+\s*$", "", clean).strip()
    norm = (
      unicodedata.normalize("NFKD", clean)
      .encode("ascii", "ignore")
      .decode("ascii")
    )
    norm = re.sub(r"[^\w\s-]", "", norm.lower())
    return re.sub(r"[-\s]+", "-", norm).strip("-_")

  def _has_renderable_schema_content(schema_obj: dict[str, Any]) -> bool:
    """Return True when `_render_table_from_schema` emits non-empty content."""
    if (
      schema_obj.get("properties")
      or "oneOf" in schema_obj
      or "$ref" in schema_obj
      or ("allOf" in schema_obj and schema_obj.get("type") != "array")
    ):
      return True
    return bool(schema_obj.get("type") or schema_obj.get("enum"))

  def _auto_ref_heading_lines(
    sub_dir: str = ".",
    _spec_file_name: str = REFERENCE_PAGE,
    include_extensions: bool = True,
    include_capability: bool = True,
    base_dir: str | None = None,
  ) -> str:
    """Return the headings `auto_generate_schema_reference` would emit.

    Mirrors `_render_reference_entry` without rendering tables, including the
    path-qualified `<span id>` anchors of vertical schemas.
    """
    if not base_dir:
      return ""
    scan_path = _normalize(Path(base_dir) / sub_dir)
    if not scan_path.is_dir():
      return ""
    lines = []
    for schema_file in sorted(
      f for f in scan_path.iterdir() if f.suffix == ".json"
    ):
      s_data = _load_json(schema_file)
      if not s_data:
        lines.append(f"### {schema_file.stem}")
        continue
      is_ext = "Extension" in s_data.get("title", "")
      if (is_ext and not include_extensions) or (
        not is_ext and not include_capability
      ):
        continue
      s_title = s_data.get("title", schema_file.stem.replace("_", " ").title())
      heading = f"### {s_title}{_reference_anchor_tag(schema_file)}"
      defs = s_data.get("$defs", {})
      if is_ext and defs:
        lines.append(heading)
        for def_name, def_schema in defs.items():
          if isinstance(def_schema, dict) and _has_renderable_schema_content(
            def_schema
          ):
            def_title = def_schema.get(
              "title", def_name.replace("_", " ").title()
            )
            anchor_tag = _reference_anchor_tag(schema_file, def_name)
            lines.append(f"#### {def_title}{anchor_tag}")
      elif _has_renderable_schema_content(s_data):
        lines.append(heading)
    return "\n".join(lines)

  _page_anchors_cache: dict[str, set[str]] = {}
  _auto_ref_re = re.compile(
    r"\{\{\s*auto_generate_schema_reference\(([^)]*)\)\s*\}\}"
  )

  def _expand_auto_ref_headings(match: re.Match[str]) -> str:
    try:
      call = ast.parse(f"f({match.group(1)})", mode="eval").body
      if not isinstance(call, ast.Call):
        return ""
      pos = [ast.literal_eval(a) for a in call.args]
      kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords if k.arg}
      return _auto_ref_heading_lines(*pos, **kw)
    except (SyntaxError, ValueError, TypeError):
      return ""

  def _spec_page_anchors(target_spec: str) -> set[str]:
    """Return HTML and heading anchor IDs on `specification/<target_spec>`."""
    key = target_spec.strip("/")
    if key in _page_anchors_cache:
      return _page_anchors_cache[key]

    md_path = SPEC_DOCS_DIR / f"{key}.md"
    if not md_path.exists():
      md_path = SPEC_DOCS_DIR / key / "index.md"
    if not md_path.exists():
      _page_anchors_cache[key] = set()
      return set()

    try:
      raw_md = md_path.read_text(encoding="utf-8")
    except OSError:
      _page_anchors_cache[key] = set()
      return set()

    raw_md = re.sub(
      r"\A---\r?\n.*?\r?\n---(?:\r?\n|\Z)", "", raw_md, flags=re.S
    )
    expanded = _auto_ref_re.sub(_expand_auto_ref_headings, raw_md)
    anchors: set[str] = set()
    used_heading_ids: set[str] = set()
    in_fence = False
    fence_marker = ""

    for line in expanded.splitlines():
      stripped = line.lstrip()
      fence_match = re.match(r"^(`{3,}|~{3,})", stripped)
      if fence_match:
        marker = fence_match.group(1)[0]
        if not in_fence:
          in_fence = True
          fence_marker = marker
          continue
        if stripped.startswith(fence_marker * 3):
          in_fence = False
          fence_marker = ""
          continue
      if in_fence:
        continue

      for html_id in re.findall(r'\bid="([^"]+)"', line):
        anchors.add(html_id)

      heading_match = re.match(r"^\s{0,3}#{1,6}\s+(.*?)\s*$", line)
      if not heading_match:
        continue
      heading_body = heading_match.group(1)
      attr_match = re.search(
        r"\{:?\s*#([A-Za-z0-9_:-]+)[^}]*\}\s*$", heading_body
      )
      if attr_match:
        slug = attr_match.group(1)
      else:
        heading_body = re.sub(
          r"\{:?\s*(?:[#\.][A-Za-z0-9_:-]+|[A-Za-z0-9_:-]+=)[^}]*\}\s*$",
          "",
          heading_body,
        )
        slug = _slugify_heading(heading_body)
      if not slug:
        continue
      unique_slug = slug
      counter = 1
      while unique_slug in used_heading_ids:
        unique_slug = f"{slug}_{counter}"
        counter += 1
      used_heading_ids.add(unique_slug)
      anchors.add(unique_slug)

    _page_anchors_cache[key] = anchors
    return anchors

  def _ref_has_real_anchor(
    ref_string: str, spec_file_name: str, ctx: RenderContext | None = None
  ) -> bool:
    """Return True if `create_link` resolves `ref_string` to a real anchor."""
    link = create_link(ref_string, spec_file_name, ctx)
    match = re.search(r"\(site:specification/([^#]+?)/?#([^)]+)\)", link)
    if not match:
      return False
    target_spec = match.group(1).rstrip("/")
    anchor = match.group(2)
    return anchor in _spec_page_anchors(target_spec)

  # --- Table rendering ---
  def _render_table_from_ref(
    properties_ref, required_list, spec_file_name, ctx
  ):
    """Inline the fields of a referenced schema.

    Args:
    ----
      properties_ref: The `$ref` to inline (optionally with `#/$defs/...`).
      required_list: The list of required properties from the parent schema.
      spec_file_name: The page the table is rendered on.
      ctx: RenderContext of the referencing schema.

    Returns:
    -------
      A string containing a Markdown table representing the schema properties,
      or a message indicating why a table could not be rendered.

    """
    ref_path = properties_ref.split("#", 1)[0].removesuffix("/schema")
    target = _resolve(ref_path or "#", ctx)
    ref_schema_data = _load_schema(target, ctx) if target else None

    if not ref_schema_data:
      # If purely external and not found locally.
      if properties_ref.startswith("http"):
        return f"_See [{properties_ref}]({properties_ref})_"
      # ucp-schema failed or schema not found - fail loudly.
      raise RuntimeError(
        f"Failed to resolve properties_ref='{properties_ref}' "
        f"{get_error_context()}. "
        "Ensure ucp-schema is installed: `cargo install ucp-schema`"
      )

    # Handle embedded anchors (e.g. file.json#/$defs/Something).
    if "#" in properties_ref and "$defs" in properties_ref:
      def_name = properties_ref.split("/")[-1]
      ref_schema_data = ref_schema_data.get("$defs", {}).get(def_name)

    if ref_schema_data and not any(
      key in ref_schema_data for key in ("properties", "allOf", "$ref")
    ):
      ref_schema_data = ref_schema_data.get("schema", ref_schema_data)

    return _render_table_from_schema(
      ref_schema_data, spec_file_name, False, required_list, ctx.at(target)
    )

  def _render_embedded_table(
    properties_list, required_list, spec_file_name, ctx, root_schema=None
  ):
    """Render the members of an `allOf` as one table.

    Args:
    ----
      properties_list: The `allOf` members.
      required_list: The list of required properties from the parent schema.
      spec_file_name: The page the table is rendered on.
      ctx: RenderContext of the composing schema.
      root_schema: Optional. Outermost schema dictionary supplying `$id` and
        `$defs` across `allOf` branches.

    Returns:
    -------
      A string containing a Markdown table representing the schema properties,
      or a message indicating why a table could not be rendered.

    """
    if not properties_list:
      return "_No content fields defined._"

    # Special handling for capability: [{"$ref": ...}, {"required": [...]}].
    if (
      len(properties_list) == 2
      and len(properties_list[1].keys()) == 1
      and "required" in properties_list[1]
    ):
      capability_required = properties_list[1].get("required", [])
      ref = properties_list[0].get("$ref")
      if ref:
        return _read_schema_from_defs(
          "capability.json" + ref,
          spec_file_name,
          False,
          capability_required,
          ctx,
        )
      # If the ref was already resolved, render the schema directly.
      return _render_table_from_schema(
        properties_list[0],
        spec_file_name,
        False,
        capability_required,
        ctx,
        root_schema=root_schema,
      )

    # Merge required arrays from all allOf siblings so that requirements
    # declared at any level surface correctly.
    merged_required = list(required_list) if required_list else []
    for item in properties_list:
      for req in item.get("required", []):
        if req not in merged_required:
          merged_required.append(req)

    blocks = []
    for properties in properties_list:
      if len(properties) == 1 and "$ref" in properties:
        blocks.append(
          _render_table_from_ref(
            properties["$ref"], merged_required, spec_file_name, ctx
          )
        )
        continue

      # Skip allOf siblings that only carry constraints (required,
      # anyOf with const-only properties) but define no new fields.
      if not (
        properties.get("properties")
        or properties.get("$ref")
        or properties.get("allOf")
      ):
        continue

      blocks.append(
        _render_table_from_schema(
          properties,
          spec_file_name,
          False,
          merged_required,
          ctx,
          root_schema=root_schema,
        )
      )

    return _dedupe_table_rows(blocks)

  def _render_table_from_schema(
    schema_data,
    spec_file_name,
    need_header=True,
    parent_required_list=None,
    ctx=None,
    *,
    root_schema=None,
  ):
    """Render a Markdown table from a schema dictionary.

    Schema dictionary must contain 'properties'. 'required' list is optional.

    Args:
    ----
      schema_data: A dictionary representing the JSON schema.
      spec_file_name: The page the table is rendered on.
      need_header: Optional. Whether to render the header row.
      parent_required_list: Optional. The list of required properties from the
        parent schema.
      ctx: Optional RenderContext (operation view and `$ref` base).
      root_schema: Optional. Outermost schema dictionary supplying `$id` and
        `$defs` across `allOf` branches.

    Returns:
    -------
      A string containing a Markdown table representing the schema properties,
      or a message indicating why a table could not be rendered.

    """
    if not schema_data:
      return "_No content fields defined._"

    ctx = (ctx or RenderContext(vertical=_page_vertical(spec_file_name))).at(
      schema_path_from_url(schema_data.get("$id"))
    )

    def link(ref):
      return create_link(ref, spec_file_name, ctx)

    # A bare "#" is a self-root reference naming the schema being rendered.
    # It carries no filename, so create_link derives an empty anchor and emits
    # a broken "<page>/##" link. Recursive refs are irreducible: ucp-schema
    # preserves them even under --bundle, so the docs layer is the only place
    # that can name them. Resolve against this schema's own $id.
    effective_root = (
      root_schema if isinstance(root_schema, dict) else schema_data
    )
    self_id = effective_root.get("$id")
    self_ref_name = self_id.rsplit("/", 1)[-1] if self_id else None

    def _deref_self(ref_value):
      if ref_value == "#" and self_ref_name:
        return self_ref_name
      return ref_value

    def _branch_ref(branch):
      # The type a composition branch names: its $ref, or the $id that bundling
      # preserved when it inlined a whole schema file.
      if not isinstance(branch, dict):
        return None
      if branch.get("$ref"):
        return _deref_self(branch["$ref"])
      if branch.get("$id") and branch is not schema_data:
        return branch["$id"]
      return None

    def _resolve_fragment_def(ref_value: str) -> dict[str, Any] | None:
      """Resolve a `#/...` or `<file>.json#/...` fragment to its raw schema."""
      if ref_value.startswith("#/"):
        target = _resolve_json_pointer(ref_value, effective_root)
        if isinstance(target, dict):
          return target
        root = _load_json(ctx.base) if ctx.base else None
        if isinstance(root, dict):
          resolved = _resolve_json_pointer(ref_value, root)
          return resolved if isinstance(resolved, dict) else None
        return None
      if "#/" in ref_value:
        file_part, frag_part = ref_value.split("#/", 1)
        root = _load_json(_resolve(file_part, ctx))
        if isinstance(root, dict):
          resolved = _resolve_json_pointer(f"#/{frag_part}", root)
          return resolved if isinstance(resolved, dict) else None
      return None

    def _is_type_branch(branch: Any) -> bool:
      """Return True when a branch carries a type instead of constraints."""
      return isinstance(branch, dict) and bool(
        _branch_ref(branch)
        or branch.get("title")
        or branch.get("type")
        or branch.get("oneOf")
        or branch.get("anyOf")
        or branch.get("allOf")
        or isinstance(branch.get("items"), dict)
        or isinstance(branch.get("additionalProperties"), dict)
      )

    def _format_schema_type(
      node: Any, *, branch_mode: bool = False, _seen: tuple[str, ...] = ()
    ) -> str:
      """Render the human-readable Type label or link for a schema node."""
      if not isinstance(node, dict):
        return "`object`" if branch_mode else "any"

      node_ref = _branch_ref(node)
      if node_ref == "#":
        node_ref = None
      if node_ref:
        if node_ref.endswith("#/$defs/version"):
          v_data = _ucp_type_index()["defs"].get("version", {})
          v_type = v_data.get("type", "string")
          return f"`{v_type}`" if branch_mode else v_type
        if "ucp.json#/$defs/" in node_ref:
          return _ucp_def_type(node_ref.split("/")[-1])
        if "#/" in node_ref:
          if _ref_has_real_anchor(node_ref, spec_file_name, ctx):
            return link(node_ref)
          if node_ref not in _seen:
            target_def = _resolve_fragment_def(node_ref)
            if isinstance(target_def, dict):
              if target_def.get("title"):
                return target_def["title"]
              return _format_schema_type(
                target_def, branch_mode=branch_mode, _seen=(*_seen, node_ref)
              )
          if node.get("title"):
            return node["title"]
        else:
          return link(node_ref)

      raw_type = node.get("type")

      if raw_type in ("object", None) and _ucp_def_name_for_title(
        node.get("title")
      ):
        return _ucp_def_type(_ucp_def_name_for_title(node["title"]))

      all_of = node.get("allOf")
      has_all_of = (
        raw_type in ("object", None)
        and isinstance(all_of, list)
        and bool(all_of)
      )
      all_of_fallback_titles: list[str] = []
      if has_all_of:
        links = []
        for branch in all_of:
          if not isinstance(branch, dict):
            continue
          b_ref = _branch_ref(branch)
          if b_ref and b_ref != "#":
            formatted = _format_schema_type(
              branch, branch_mode=False, _seen=_seen
            )
            if "](" in formatted:
              links.append(formatted)
            elif formatted not in ("any", "object"):
              all_of_fallback_titles.append(formatted)
          elif branch.get("title"):
            all_of_fallback_titles.append(branch["title"])
          elif branch_mode and branch.get("x-ucp-def-name"):
            all_of_fallback_titles.append(branch["x-ucp-def-name"])
        if len(links) == 1:
          return links[0]
        if links:
          return f"AllOf[{', '.join(links)}]"

      if raw_type in ("object", None) and node.get("title"):
        untitled = {k: v for k, v in node.items() if k != "title"}
        structural = _format_schema_type(
          untitled, branch_mode=branch_mode, _seen=_seen
        )
        if "](" in structural:
          return structural
        return node["title"]

      # A oneOf whose branches only carry validation constraints (e.g. the
      # `required`/`not` rules on food `tip.json`) names no type; skip it so
      # the node's own type or title still renders.
      if isinstance(node.get("oneOf"), list) and any(
        _is_type_branch(b) for b in node["oneOf"]
      ):
        parts = [
          _format_schema_type(b, branch_mode=True, _seen=_seen)
          for b in node["oneOf"]
        ]
        return f"OneOf[{', '.join(parts)}]"

      if (
        isinstance(node.get("anyOf"), list)
        and node["anyOf"]
        and not node.get("properties")
      ):
        typed_branches = [b for b in node["anyOf"] if _is_type_branch(b)]
        if typed_branches:
          parts = [
            _format_schema_type(b, branch_mode=True, _seen=_seen)
            for b in typed_branches
          ]
          return f"AnyOf[{', '.join(parts)}]"

      if raw_type == "array" or (
        raw_type is None
        and isinstance(node.get("items"), dict)
        and node["items"]
      ):
        items = node.get("items")
        if isinstance(items, dict) and items:
          inner = _format_schema_type(items, branch_mode=False, _seen=_seen)
          if inner == "any":
            inner = "object"
          return f"Array[{inner}]"
        return "`array`" if branch_mode else "array"

      if (
        raw_type in ("object", None)
        and not node.get("properties")
        and isinstance(node.get("additionalProperties"), dict)
        and node["additionalProperties"]
      ):
        val_type = _format_schema_type(
          node["additionalProperties"], branch_mode=False, _seen=_seen
        )
        if val_type == "any":
          val_type = "object"
        return f"Map[string, {val_type}]"

      if has_all_of and not node.get("properties"):
        if len(all_of_fallback_titles) == 1:
          return all_of_fallback_titles[0]
        branch_types = {
          branch["type"]
          for branch in all_of
          if isinstance(branch, dict) and branch.get("type") is not None
        }
        if len(branch_types) == 1:
          shared = branch_types.pop()
          return f"`{shared}`" if branch_mode else shared
        if branch_mode:
          nested = {
            _format_schema_type(b, branch_mode=False, _seen=_seen)
            for b in all_of
            if isinstance(b, dict)
          } - {"any"}
          if len(nested) == 1:
            only = nested.pop()
            if only in (
              "object",
              "array",
              "string",
              "number",
              "integer",
              "boolean",
              "null",
            ):
              return f"`{only}`"
            return only
          return "`object`"

      if isinstance(raw_type, str):
        return f"`{raw_type}`" if branch_mode else raw_type
      if isinstance(raw_type, list) and raw_type:
        return f"OneOf[{', '.join(f'`{t}`' for t in raw_type)}]"
      return "`object`" if branch_mode else "any"

    # If schema is ONLY a oneOf, render as prose instead of table.
    if (
      "oneOf" in schema_data
      and not schema_data.get("properties")
      and not schema_data.get("allOf")
      and not schema_data.get("$ref")
    ):
      links = [
        _format_schema_type(item, branch_mode=True)
        for item in schema_data["oneOf"]
      ]
      if links:
        return (
          "\nThis object MUST be one of the following types: "
          + ", ".join(links)
          + ".\n"
        )

    properties = schema_data.get("properties", {})
    required_list = schema_data.get("required", [])

    if parent_required_list:
      # Preserve required fields from both the embedded child schema and the
      # parent wrapper that referenced it.
      required_list = list(required_list)
      for req in parent_required_list:
        if req not in required_list:
          required_list.append(req)

    if (
      not properties
      and "oneOf" not in schema_data
      and "$ref" not in schema_data
      and ("allOf" not in schema_data or schema_data.get("type") == "array")
    ):
      # Fallback for scalar schemas (Enums, Strings with patterns, etc.).
      s_type = schema_data.get("type")
      enum_val = schema_data.get("enum")
      pattern_val = schema_data.get("pattern")

      if s_type or enum_val:
        desc = schema_data.get("description", "")
        if pattern_val:
          desc += f"\n\n**Pattern:** `{pattern_val}`"
        if enum_val:
          formatted = ", ".join([f"`{v}`" for v in enum_val])
          desc += f"\n\n**Enum:** {formatted}"
        return desc

      return "_No properties defined._"

    md = []
    if need_header:
      md = ["| Name | Type | Requirement | Description |"]
      md.append("| :--- | :--- | :--- | :--- |")

    if "allOf" in properties:
      md.append(
        _render_embedded_table(
          properties.get("allOf", []),
          required_list,
          spec_file_name,
          ctx,
          root_schema=effective_root,
        )
      )
      return "\n".join(md)

    if "allOf" in schema_data:
      all_of_list = list(schema_data.get("allOf", []))
      if properties:
        all_of_list.append(
          {
            "properties": properties,
            "required": schema_data.get("required", []),
          }
        )
      md.append(
        _render_embedded_table(
          all_of_list,
          required_list,
          spec_file_name,
          ctx,
          root_schema=effective_root,
        )
      )
      return "\n".join(md)

    if "$ref" in schema_data:
      md.append(
        _render_table_from_ref(
          schema_data.get("$ref"), required_list, spec_file_name, ctx
        )
      )
      return "\n".join(md)

    for field_name, details in properties.items():
      if field_name == "$ref":
        md.append(
          _render_table_from_ref(details, required_list, spec_file_name, ctx)
        )
        continue

      # Capture the request-requirement annotation before `details` may be
      # reassigned during $ref resolution below.
      ucp_annotation = (
        details.get("ucp_request") if isinstance(details, dict) else None
      )

      ref = _branch_ref(details)

      # Resolve UCP $defs references inline so properties render with
      # descriptions/constants from ucp.json while preserving links.
      # e.g., "$ref": "../../ucp.json#/$defs/error" -> inline the allOf
      ucp_def_override = None
      if ref and "ucp.json#/$defs/" in ref:
        def_name = ref.split("/")[-1]
        resolved_def = _ucp_type_index()["defs"].get(def_name)
        if isinstance(resolved_def, dict):
          embedder_desc = details.get("description")
          details = dict(resolved_def)
          if embedder_desc:
            details["description"] = embedder_desc
          ref = None
          ucp_def_override = details.get("type") or _ucp_def_type(def_name)

      # Special handling for UCP version.
      version_data = None
      if ref and ref.endswith("#/$defs/version"):
        version_data = _ucp_type_index()["defs"].get("version", {})

      # --- Logic to determine Display Type ---
      if ucp_def_override is not None:
        f_type = ucp_def_override
      elif version_data:
        f_type = version_data.get("type", "any")
      else:
        f_type = _format_schema_type(details)

      # --- Handle Description ---
      desc = ""
      # Handle additional description text for constant.
      if "const" in details:
        desc += f"**Constant = {details.get('const')}**. "
      # Special handling for UCP version.
      elif version_data and ref == "#/$defs/version":
        desc += version_data.get("description", "")

      # Get embedder's description, or inherit from ref'd type if omitted.
      embedder_desc = details.get("description")
      if embedder_desc is not None:
        desc += embedder_desc
      elif ref and not ref.startswith("#"):
        ref_schema = _load_json(_resolve(ref, ctx))
        if ref_schema:
          desc += ref_schema.get("description", "")

      # --- Handle Enum ---
      enum_values = details.get("enum")
      if enum_values and isinstance(enum_values, list):
        # Format values like: `val1`, `val2`.
        formatted_enums = ", ".join([f"`{str(v)}`" for v in enum_values])
        # Add a line break if description exists, then append Enum list.
        if desc:
          desc += "<br>"
        desc += f"**Enum:** {formatted_enums}"

      # --- Handle Requirement (per request op + response) ---
      requirement = _field_requirement(
        field_name, ucp_annotation, required_list
      )

      md.append(f"| {field_name} | {f_type} | {requirement} | {desc} |")

    return "\n".join(md)

  def _read_schema_from_defs(
    entity_name,
    spec_file_name,
    need_header=True,
    parent_required_list=None,
    ctx=None,
  ):
    """Render a table for a `<file>.json#/<pointer>` definition.

    Args:
    ----
      entity_name: e.g. 'discount.json#/$defs/allocation'. The file part is
        resolved relative to `ctx.base`, else by name within the vertical.
      spec_file_name: The page the table is rendered on.
      need_header: Whether to render the header row (and description).
      parent_required_list: Required properties from the parent schema.
      ctx: Optional RenderContext of the caller.

    """
    if ".json#/" not in entity_name:
      raise ValueError(
        f"Invalid entity name format for def: {entity_name}"
        f"{get_error_context()}"
      )
    file_part, pointer = entity_name.split(".json#", 1)
    file_part += ".json"
    pointer = "#" + pointer

    ctx = ctx or RenderContext(vertical=_page_vertical(spec_file_name))
    full_path = _resolve(file_part, ctx)
    if full_path is None:
      raise FileNotFoundError(
        f"Schema file '{file_part}' not found in any schema"
        f" directory{get_error_context()}."
      )

    # Use ucp-schema to resolve the full file with bundling.
    bundled = _resolve_schema(full_path, bundle=True)
    embedded_schema_data = _resolve_json_pointer(pointer, bundled)
    if embedded_schema_data is None:
      raise RuntimeError(
        f"Definition '{pointer}' not found in '{full_path}'"
        f"{get_error_context()}"
      )
    # Resolve internal refs (like #/$defs/base) against the bundled root.
    embedded_schema_data = _resolve_internal_all_of(
      embedded_schema_data, bundled
    )
    # Bundling drops cross-file $refs and $ids; restore them for links.
    raw_root = _resolve_schema(full_path)
    raw_def = (
      _resolve_json_pointer(pointer, raw_root)
      if isinstance(raw_root, dict)
      else None
    )
    table_ctx = RenderContext(base=full_path, vertical=ctx.vertical)
    embedded_schema_data = _restore_fragment_refs(
      embedded_schema_data,
      raw_def,
      full_path,
      raw_root,
      anchor_checker=lambda ref: _ref_has_real_anchor(
        ref, spec_file_name, table_ctx
      ),
    )

    table = _render_table_from_schema(
      embedded_schema_data,
      spec_file_name,
      need_header,
      parent_required_list,
      table_ctx,
    )
    desc = embedded_schema_data.get("description", "")
    # Scalar schemas (a string/enum with no properties or composition) already
    # embed their description in the rendered fallback table; prepending it
    # here would duplicate it. Only structured schemas — whose table is a
    # property grid that omits the description — need the description
    # prepended.
    is_structured = any(
      key in embedded_schema_data
      for key in ("properties", "allOf", "oneOf", "$ref")
    )
    if desc and need_header and is_structured:
      return f"{desc}\n\n{table}"
    return table

  def _resolves_to_shared_type(ref_path):
    """Return path if ref_path identifies a `common/types/` primitive.

    Scope is intentionally narrow: only schemas under
    `source/schemas/common/types/` have canonical entries eligible for
    link-only rendering on capability pages. Callers render fields inline by
    default and use this lookup only when they explicitly opt out.

    Vertical-namespaced types under `<vertical>/types/` always render inline
    because they have no canonical shared-type entry. Render duplication is
    safe because every table is generated from the same JSON source.

    Cross-references emitted inside any rendered table continue to
    route to `reference.md` via `create_link` (the redirect rule
    introduced in #226 is unchanged), so anchor consistency holds
    end-to-end regardless of which pages render a given type inline.

    This lookup assumes that filenames at `common/` root remain
    disjoint from `common/types/`. If a future schema introduces a
    basename collision, the rule here will need explicit
    disambiguation.
    """
    name = Path(str(ref_path).split("#", 1)[0]).stem
    candidate = COMMON_TYPES_DIR / (name + ".json")
    return candidate if candidate.exists() else None

  def _render_shared_type_link(canonical_name, spec_file_name):
    """Emit a Markdown link to the `reference.md` entry for a shared type.

    Used in place of inline-rendering a `common/types/` table on a
    capability page (#412). `create_link` already routes `common/` schemas
    to `reference.md`, so we reuse it to keep the anchor scheme
    consistent with cross-references emitted from inside other tables.

    `canonical_name` must be the suffix-stripped base name (with or
    without a leading `types/`), never the raw macro argument.
    `reference.md` emits exactly one anchor per schema file -- one
    heading per file, one anchor per heading -- and does not emit
    per-variant anchors. A raw argument still carrying an operation suffix would
    cause `create_link` to bake the variant into the anchor and target
    a heading that does not exist on `reference.md`.
    """
    # Normalize canonical_name into a ref-style path so create_link's
    # anchor logic matches the heading produced by
    # auto_generate_schema_reference on reference.md.
    ref = (
      canonical_name
      if canonical_name.startswith("types/")
      else f"types/{canonical_name}"
    )
    if not ref.endswith(".json"):
      ref = ref + ".json"
    link = create_link(ref, spec_file_name)
    # The trailing reference must use the `site:` absolute scheme
    # (handled by the site-urls plugin), not a relative `reference.md`
    # link. A relative link resolves from the source file's directory,
    # so callers from any subdirectory page would otherwise target a
    # non-existent `<subdir>/reference.md`.
    return (
      f"See {link} in the [Schema Reference](site:specification/reference/) "
      f"for the canonical field definition."
    )

  # --- MACRO 1: For Standalone JSON Schemas ---
  @env.macro
  def schema_fields(entity_name, spec_file_name, render_inline=True):
    """Parse a standalone JSON Schema file and render a table.

    Usage: {{ schema_fields('buyer', 'shopping/checkout') }}

    Suffixes control schema resolution direction:
    - 'cart_resp' -> resolves cart.json as response schema
    - 'cart_create_req' -> resolves cart.json as request schema (op=create)
    - 'buyer' -> resolves buyer.json as response schema (default)

    Bare names resolve within the calling page's vertical (e.g. 'buyer' on a
    food page is food/types/buyer.json); names may also be qualified
    ('food/types/buyer', 'types/context').

    For schemas under `common/types/` (cross-vertical primitives),
    callers from pages other than `reference.md` can selectively receive a
    Markdown link to the canonical entry on `reference.md` or an
    inline table based on the `render_inline` value.

    Args:
    ----
      entity_name: Schema name with optional suffix (e.g., 'cart_resp').
      spec_file_name: Spec page for link generation (e.g., 'shopping/cart').
      render_inline: A boolean that determines whether common types
        should be rendered inline or redirect to reference.md. Has a
        default value of True to always force inline rendering.

    """
    base_name, direction, operation = parse_entity_name(entity_name)

    # By default, `render_inline` is always true to promote better readability,
    # but callers can override it to false to explicitly trigger the redirect
    # rendering for `common/types` schemas. reference.md itself always renders
    # full tables via auto_generate_schema_reference. base_name is passed
    # (suffix stripped) so the link anchor targets the canonical heading.
    if (
      not render_inline
      and spec_file_name != REFERENCE_PAGE
      and _resolves_to_shared_type(base_name) is not None
    ):
      return _render_shared_type_link(base_name, spec_file_name)

    ctx = RenderContext(
      io_type=direction,
      operation_id=operation,
      vertical=_page_vertical(spec_file_name),
    )
    full_path = _resolve(base_name, ctx)
    if full_path is None:
      raise FileNotFoundError(
        f"Schema '{base_name}' not found in any schema directory"
        f"{get_error_context()}."
      )

    # Resolve WITHOUT bundling to preserve $refs for hyperlinks.
    resolved_schema = _resolve_schema(full_path, direction, operation)
    parent_required = None
    base_schema = _variant_base(full_path)
    if resolved_schema and base_schema is not None:
      resolved_schema, parent_required = _inherit_base_fields(
        resolved_schema, base_schema
      )
    return _render_table_from_schema(
      resolved_schema,
      spec_file_name,
      parent_required_list=parent_required,
      ctx=ctx.at(full_path),
    )

  @env.macro
  def extension_schema_fields(entity_name, spec_file_name, render_inline=True):
    """Render a table for a definition inside a JSON Schema file.

    Usage:
      {{ extension_schema_fields('fulfillment.json#/$defs/fulfillment_option',
                                 'shopping/extensions/fulfillment') }}

    When the embedded schema lives under `common/types/` and `render_inline` is
    False, the macro emits a link to the canonical entry on `reference.md`
    instead of render the table inline. Vertical-namespaced extensions
    always render inline.

    Args:
    ----
      entity_name: The name of the schema entity embedded in the extension
        (e.g., 'fulfillment.json#/$defs/fulfillment_option').
      spec_file_name: The name of the spec file indicating where the dictionary
        should be rendered (e.g., "shopping/checkout").
      render_inline: A boolean that determines whether common types should be
        rendered inline or redirect to reference.md. Has a default value
        of True to always force inline rendering.

    """
    # Redirect to reference.md only when `<file>.json` resolves to a
    # `common/types/` schema and `render_inline` is False; vertical-namespaced
    # extensions keep their inline render so same-page `$defs` anchors
    # continue to resolve.
    if (
      not render_inline
      and spec_file_name != REFERENCE_PAGE
      and ".json#" in entity_name
      and _resolves_to_shared_type(entity_name.split(".json#", 1)[0])
    ):
      return create_link(entity_name, spec_file_name)
    return _read_schema_from_defs(entity_name, spec_file_name)

  def _render_reference_entry(schema_file, schema_data, spec_file_name):
    """Render one auto-generated reference entry (lines), or [] to skip."""
    title = schema_data.get("title", schema_file.stem.replace("_", " ").title())
    ctx = RenderContext(base=schema_file, vertical=vertical_of(schema_file))
    heading = f"### {title}{_reference_anchor_tag(schema_file)}\n"

    defs = schema_data.get("$defs", {})
    is_extension = "Extension" in schema_data.get("title", "")
    if is_extension and defs:
      lines = [heading]
      rel_path = schema_file.relative_to(SCHEMAS_DIR).as_posix()
      for def_name, def_schema in defs.items():
        table = _read_schema_from_defs(
          f"{rel_path}#/$defs/{def_name}", spec_file_name, ctx=ctx
        )
        if table == "_No properties defined._":
          continue
        def_title = def_schema.get("title", def_name.replace("_", " ").title())
        anchor_tag = _reference_anchor_tag(schema_file, def_name)
        lines += [f"#### {def_title}{anchor_tag}\n", table, "\n"]
      return [*lines, "\n---\n"]

    if is_extension and not any(
      schema_data.get(key) for key in ("properties", "allOf", "oneOf", "$ref")
    ):
      return []

    parent_required = None
    base_schema = _variant_base(schema_file)
    if base_schema is not None:
      schema_data, parent_required = _inherit_base_fields(
        schema_data, base_schema
      )
    table = _render_table_from_schema(
      schema_data,
      spec_file_name,
      parent_required_list=parent_required,
      ctx=ctx,
    )
    if table == "_No properties defined._":
      return []
    return [heading, table, "\n---\n"]

  @env.macro
  def auto_generate_schema_reference(
    sub_dir=".",
    spec_file_name=REFERENCE_PAGE,
    include_extensions=True,
    include_capability=True,
    base_dir=None,
  ):
    """Scan a dir for JSON schemas and generate documentation.

    Scan a subdirectory for .json files and generate documentation for each
    schema found. Headings of vertical schemas also carry a path-qualified
    anchor (e.g. `#food-types-fulfillment`) used by cross-reference links,
    since titles may collide across and within verticals.

    Args:
    ----
      sub_dir: The subdirectory to scan, relative to base_dir.
      spec_file_name: The name of the spec file for link generation.
      include_extensions: If true, includes schemas with 'Extension' in title.
      include_capability: If true, includes schemas without 'Extension' in
        title.
      base_dir: The namespace directory to scan, e.g. 'source/schemas/common'
        or 'source/schemas/food'. Required.

    """
    if not base_dir:
      raise ValueError(
        "auto_generate_schema_reference requires base_dir (e.g. "
        f"'source/schemas/common'){get_error_context()}."
      )
    scan_path = _normalize(Path(base_dir) / sub_dir)
    if not scan_path.is_dir():
      return f"<p><em>Schema directory not found: {scan_path}</em></p>"

    schema_files = sorted(f for f in scan_path.iterdir() if f.suffix == ".json")
    if not schema_files:
      return f"<p><em>No schema files found in {scan_path}</em></p>"

    output = []
    for schema_file in schema_files:
      schema_data = _load_json(schema_file)
      if not schema_data:
        output += [
          f"### {schema_file.stem}\n",
          f"<p><em>Could not load schema for entity: {schema_file}</em></p>",
          "\n---\n",
        ]
        continue
      is_extension = "Extension" in schema_data.get("title", "")
      if (is_extension and not include_extensions) or (
        not is_extension and not include_capability
      ):
        continue
      output += _render_reference_entry(
        schema_file, schema_data, spec_file_name
      )

    return "\n".join(output)

  # --- MACRO 2: For Standalone JSON Extensions ---
  @env.macro
  def extension_fields(entity_name, spec_file_name, target="checkout"):
    """Parse an extension schema file and render a table from its $defs.

    Usage: {{ extension_fields('discount', 'shopping/extensions/discount') }}

    Args:
    ----
      entity_name: The name of the extension schema (e.g., 'discount'),
        resolved within the calling page's vertical.
      spec_file_name: The name of the spec file indicating where the dictionary
        should be rendered (e.g., "shopping/extensions/fulfillment").
      target: Optional. The core schema name that is being extended (e.g.,
        "checkout", "cart"). Defaults to "checkout".

    """
    ctx = RenderContext(vertical=_page_vertical(spec_file_name))
    full_path = _resolve(entity_name, ctx)
    data = _load_json(full_path)
    if data is None:
      raise RuntimeError(
        f"Error loading extension '{entity_name}'{get_error_context()}"
      )
    ctx = ctx.at(full_path)

    # Extension schemas have their composed type in $defs, keyed by the
    # extended schema (e.g. `checkout` or `dev.ucp.shopping.checkout`).
    composed = [
      (key, schema_def)
      for key, schema_def in data.get("$defs", {}).items()
      if isinstance(schema_def, dict) and "allOf" in schema_def
    ]
    # Prefer the requested target, then fall back to any composed type.
    preferred = [
      schema_def
      for key, schema_def in composed
      if key == target or key.endswith("." + target)
    ]
    for schema_def in preferred[:1] + [d for _, d in composed]:
      for item in schema_def["allOf"]:
        if "properties" in item:
          return _render_table_from_schema(item, spec_file_name, ctx=ctx)

    raise RuntimeError(
      f"Could not find extension properties for target '{target}' "
      f"in '{entity_name}'{get_error_context()}"
    )

  # --- MACRO 3: For Transport Operations ---
  @env.macro
  def method_fields(operation_id, file_name, spec_file_name, io_type=None):
    """Extract Request/Response schemas for a specific OpenAPI operationId.

    Args:
    ----
      operation_id: The `operationId` of the OpenAPI operation to document.
      file_name: The name of the OpenAPI file to read.
      spec_file_name: The name of the spec file indicating where the dictionary
        should be rendered (e.g., "shopping/checkout").
      io_type: Optional. Specifies whether to render 'request', 'response', or
        both (if None).

    """
    try:
      data = _load_openapi(file_name)
    except (FileNotFoundError, json.JSONDecodeError) as e:
      raise RuntimeError(
        f"Error processing OpenAPI: {e}{get_error_context()}"
      ) from e

    # 1. Find the Operation Object by ID (search paths first, then webhooks).
    operation, path_parameters = _find_operation(
      data, operation_id, include_webhooks=True
    )
    if not operation:
      raise ValueError(
        f"Operation ID `{operation_id}` not found{get_error_context()}."
      )

    # 2. Extract Request Schema.
    req_content = operation.get("requestBody", {}).get("content", {})
    req_schema = req_content.get("application/json", {}).get("schema", {})

    # 3. Extract Parameters (Path + Operation).
    all_parameters = path_parameters + operation.get("parameters", [])

    # 4. Extract Response Schema.
    res_schema = {}
    responses = operation.get("responses", {})
    for code in ("200", "201"):
      if code in responses:
        res_content = responses[code].get("content", {})
        res_schema = res_content.get("application/json", {}).get("schema", {})
        break

    # Targeted reference resolution: only resolve the top-level ref and
    # 'allOf' children (e.g. "complete_checkout") without expanding every
    # property.
    def resolve_structure(schema):
      if not schema:
        return schema
      if "$ref" in schema and schema["$ref"].startswith("#/"):
        schema = _resolve_json_pointer(schema["$ref"], data) or schema
      return _resolve_internal_all_of(schema, data)

    req_schema = resolve_structure(req_schema)
    res_schema = resolve_structure(res_schema)

    # Refs inside the OpenAPI document are relative to the OpenAPI file.
    base_ctx = RenderContext(
      operation_id=operation_id,
      base=_normalize(OPENAPI_DIR / file_name),
      vertical=_page_vertical(spec_file_name),
    )
    output = ""

    # -- Render Request --
    if io_type is None or io_type == "request":
      param_props = {}
      param_required_fields = []
      for param in all_parameters:
        # Resolve param refs explicitly if needed.
        if "$ref" in param and param["$ref"].startswith("#/"):
          param = _resolve_json_pointer(param["$ref"], data) or param

        # Filter out headers (transport-specific).
        if param.get("in") == "header":
          continue
        name = param.get("name", "")
        if not name:
          continue

        # Convert to schema property format.
        prop_schema = param.get("schema", {}).copy()
        if "description" in param:
          prop_schema["description"] = param["description"]

        # Add additional annotation for path parameters.
        if param.get("in", "") == "path":
          prop_schema["description"] = (
            prop_schema.get("description", "") + "Defined in path."
          )
        param_props[name] = prop_schema
        if param.get("required"):
          param_required_fields.append(name)

      param_schema = None
      if param_props:
        param_schema = {
          "properties": param_props,
          "required": param_required_fields,
        }

      # 5. Combine Parameters and Request Body into a single "Inputs" schema.
      if param_schema and req_schema:
        combined_schema = {"properties": {"allOf": [param_schema, req_schema]}}
      else:
        combined_schema = param_schema or req_schema

      if combined_schema:
        req_ctx = dataclasses.replace(base_ctx, io_type="request")
        output += "**Inputs**\n\n"
        output += (
          _render_table_from_schema(
            combined_schema, spec_file_name, ctx=req_ctx
          )
          + "\n\n"
        )
      else:
        output += "_No inputs defined._\n\n"

    # -- Render Output --
    if io_type is None or io_type == "response":
      if res_schema:
        if io_type is None:
          output += "**Output**\n\n"
        res_ctx = dataclasses.replace(base_ctx, io_type="response")
        output += (
          _render_table_from_schema(res_schema, spec_file_name, ctx=res_ctx)
          + "\n\n"
        )
      else:
        output += "_No output defined._\n\n"

    return output

