# Cache for resolved schemas to avoid repeated subprocess calls.
_resolved_schema_cache: dict[str, dict] = {}


def _load_json(path: str | Path | None) -> dict[str, Any] | None:
  """Load JSON file, returns None on error."""
  if path is None:
    return None
  try:
    with Path(path).open(encoding="utf-8") as f:
      return json.load(f)
  except (json.JSONDecodeError, OSError):
    return None


def _resolve_json_pointer(pointer: str, data: Any) -> Any | None:
  """Navigate to a JSON pointer path (e.g., '#/$defs/foo' or '#/components/x').

  Args:
  ----
    pointer: JSON pointer starting with '#' (e.g., '#/$defs/allocation').
    data: The JSON data to navigate.

  Returns:
  -------
    The value at the pointer path, or None if not found.

  """
  if pointer == "#":
    return data
  if not pointer.startswith("#/"):
    return None

  current = data
  for part in pointer[2:].split("/"):
    if isinstance(current, dict) and part in current:
      current = current[part]
    elif isinstance(current, list):
      try:
        current = current[int(part)]
      except (ValueError, IndexError):
        return None
    else:
      return None
  return current


def _resolve_internal_all_of(schema: dict, root: Any) -> dict:
  """Inline `allOf` members that are internal (`#/...`) refs into `root`."""
  if "allOf" not in schema:
    return schema
  resolved_all_of = []
  for item in schema["allOf"]:
    if "$ref" in item and item["$ref"].startswith("#"):
      resolved = _resolve_json_pointer(item["$ref"], root)
      resolved_all_of.append(resolved if resolved else item)
    else:
      resolved_all_of.append(item)
  return {**schema, "allOf": resolved_all_of}


def _resolve_schema(
  schema_path: str | Path,
  direction: str = "response",
  operation: str = "read",
  bundle: bool = False,
) -> dict[str, Any] | None:
  """Resolve a schema using ucp-schema CLI.

  Args:
  ----
    schema_path: Path to the schema file.
    direction: 'request' or 'response'.
    operation: 'create', 'update', 'complete', or 'read'.
    bundle: If True, inline all $ref pointers. If False, preserve $refs for
      hyperlink generation in documentation.

  Returns:
  -------
    Resolved schema as dict, or raises RuntimeError if ucp-schema fails.

  """
  bundle_suffix = ":bundled" if bundle else ""
  resolved_path = Path(schema_path).resolve()
  cache_key = f"{resolved_path}:{direction}:{operation}{bundle_suffix}"
  if cache_key in _resolved_schema_cache:
    return _resolved_schema_cache[cache_key]

  dir_flag = "--request" if direction == "request" else "--response"
  cmd = ["ucp-schema", "resolve", str(schema_path), dir_flag, "--op", operation]
  if bundle:
    cmd.append("--bundle")

  result = subprocess.run(cmd, capture_output=True, text=True, check=False)
  if result.returncode != 0:
    raise RuntimeError(f"ucp-schema execution error: result = {result}")
  data = json.loads(result.stdout)
  _resolved_schema_cache[cache_key] = data
  return data


def _resolve_schema_bundled(
  schema_path: str | Path,
  direction: str = "response",
  operation: str = "read",
) -> dict[str, Any] | None:
  """Resolve a schema with bundling (backward compat)."""
  return _resolve_schema(schema_path, direction, operation, bundle=True)


# --- RENDER CONTEXT ---


@dataclasses.dataclass(frozen=True)
class RenderContext:
  """State threaded through recursive table rendering.

  Attributes:
    io_type: 'request' or 'response' to render an operation-specific view
      (resolved through ucp-schema); None renders schemas as authored.
    operation_id: Operation (or operationId) selecting the ucp-schema `--op`.
    base: Schema/OpenAPI file whose relative `$ref`s are being rendered.
    vertical: Vertical of the calling page, used to resolve bare schema
      names when `base` cannot.

  """

  io_type: str | None = None
  operation_id: str = ""
  base: Path | None = None
  vertical: str | None = None

  def at(self, base: Path | None) -> "RenderContext":
    """Return a copy rendering refs relative to `base` (if given)."""
    return dataclasses.replace(self, base=base) if base else self

  @property
  def lookup_vertical(self) -> str | None:
    """Vertical used for name-based lookups: the base's, else the page's."""
    return vertical_of(self.base) or self.vertical

  @property
  def operation(self) -> str:
    """The ucp-schema `--op` value for this context."""
    if self.io_type != "request":
      return "read"
    op_id = self.operation_id.lower()
    if "create" in op_id:
      return "create"
    if "update" in op_id or "patch" in op_id:
      return "update"
    if "complete" in op_id:
      return "complete"
    return "read"


